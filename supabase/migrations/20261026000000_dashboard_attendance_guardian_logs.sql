alter table public.staff_users
  add column if not exists type text;

alter table public.appointments
  add column if not exists is_guardian_booking boolean not null default false,
  add column if not exists guardian_name text,
  add column if not exists guardian_relationship text,
  add column if not exists guardian_contact text,
  add column if not exists cancellation_reason text,
  add column if not exists cancelled_at timestamptz;

create table if not exists public.staff_attendance (
  id bigint generated by default as identity primary key,
  staff_user_id bigint not null,
  attendance_date date not null,
  clock_in timestamptz not null,
  clock_out timestamptz,
  created_at timestamptz not null default now(),
  unique (staff_user_id, attendance_date),
  check (clock_out is null or clock_out >= clock_in)
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_user_id bigint,
  actor_name text not null default 'System',
  actor_role text not null default 'system',
  action text not null,
  target_type text,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists staff_attendance_date_idx
  on public.staff_attendance (attendance_date, staff_user_id);
create index if not exists activity_logs_created_at_idx
  on public.activity_logs (created_at desc);
