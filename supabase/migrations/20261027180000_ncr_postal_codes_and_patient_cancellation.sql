create table if not exists public.postal_codes (
  id bigint generated by default as identity primary key,
  country_code text not null,
  region_code text not null,
  city_code text not null,
  city_name text not null,
  postal_code text not null,
  constraint postal_codes_city_unique unique (country_code, region_code, city_code)
);

alter table public.postal_codes enable row level security;

drop policy if exists postal_codes_public_read on public.postal_codes;
create policy postal_codes_public_read
on public.postal_codes
for select
to anon, authenticated
using (true);

grant select on public.postal_codes to anon, authenticated;

