create or replace function public.cancel_patient_appointment(p_appointment_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.appointments appointment
  set
    status = 'Cancelled',
    cancellation_reason = 'Patient requested rescheduling',
    cancelled_at = now()
  where appointment.id = p_appointment_id
    and appointment.status in ('Pending', 'Accepted')
    and appointment.appointment_date > (now() at time zone 'Asia/Manila')::date
    and exists (
      select 1
      from public.staff_users patient
      where patient.id = appointment.patient_id
        and patient.role = 'patient'
        and patient.auth_user_id = (select auth.uid())
    );

  return found;
end;
$$;

revoke all on function public.cancel_patient_appointment(bigint) from public, anon;
grant execute on function public.cancel_patient_appointment(bigint) to authenticated;

create or replace function public.prevent_patient_cancellation_on_or_after_appointment_date()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status in ('Pending', 'Accepted')
    and new.status = 'Cancelled'
    and exists (
      select 1
      from public.staff_users patient
      where patient.id = old.patient_id
        and patient.role = 'patient'
        and patient.auth_user_id = (select auth.uid())
    )
    and old.appointment_date <= (now() at time zone 'Asia/Manila')::date
  then
    raise exception 'Patient appointments can only be cancelled before the scheduled date.'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists prevent_patient_cancellation_on_or_after_appointment_date
on public.appointments;

create trigger prevent_patient_cancellation_on_or_after_appointment_date
before update of status on public.appointments
for each row
execute function public.prevent_patient_cancellation_on_or_after_appointment_date();
